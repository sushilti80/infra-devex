import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const directory = path.dirname(fileURLToPath(import.meta.url));
const marker = '# Generated by infra-devex catalog v1';
const safeName = /^[a-z0-9][a-z0-9-]{0,39}$/;

export function generate({ repository, project, environment, modules }) {
  project = String(project || '').toLowerCase();
  environment = String(environment || '').toLowerCase();
  if (!safeName.test(project) || !safeName.test(environment)) throw new Error('Invalid project or environment');
  const catalog = JSON.parse(fs.readFileSync(path.join(directory, 'modules.json'), 'utf8'));
  if (catalog.schemaVersion !== 1) throw new Error('Unsupported catalog schema');
  const available = new Map(catalog.modules.map(m => [m.id.toLowerCase(), m]));
  const selected = String(modules || '').split(',').map(x => x.trim().toLowerCase()).filter(Boolean);
  if (!selected.length) throw new Error('Select at least one catalog module');
  const ordered = [];
  const visited = new Set();
  const visiting = new Set();
  function visit(id) {
    if (visited.has(id)) return;
    if (visiting.has(id)) throw new Error(`Circular dependency: ${id}`);
    const item = available.get(id);
    if (!item) throw new Error(`Unsupported module: ${id}`);
    if (!/^git::https:\/\/github\.com\/Azure\/[a-z0-9-]+\.git\?ref=[0-9a-f]{40}$/i.test(item.source)) throw new Error('Invalid pinned module source');
    visiting.add(id);
    for (const dep of item.dependencies) visit(dep.toLowerCase());
    visiting.delete(id);
    visited.add(id);
    ordered.push(item);
  }
  selected.forEach(visit);
  const envDir = path.join(path.resolve(repository), 'infrastructure', project, environment);
  if (fs.existsSync(envDir)) {
    for (const entry of fs.readdirSync(envDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const candidate = path.join(envDir, entry.name, 'terragrunt.hcl');
      if (fs.existsSync(candidate) && !fs.readFileSync(candidate, 'utf8').startsWith(marker)) {
        throw new Error(`Existing module ${entry.name} is not managed by catalog v1; migrate separately`);
      }
    }
  }
  const hash = crypto.createHash('sha256').update(`${project}/${environment}`).digest('hex').slice(0, 8);
  const account = `${(project + environment).replace(/[^a-z0-9]/g, '').slice(0, 16)}${hash}`;
  const root = 'include "root" {\n  path = find_in_parent_folders("root.hcl")\n}\n\nlocals {\n  env = read_terragrunt_config(find_in_parent_folders("env.hcl"))\n}\n';
  const pending = [];
  for (const item of ordered) {
    const id = item.id.toLowerCase();
    if (!/^[a-z0-9-]+\.hcl$/.test(item.template)) throw new Error('Invalid template name');
    const variables = { project, environment, storage_name: account };
    const template = fs.readFileSync(path.join(directory, 'templates', item.template), 'utf8');
    const extra = template.replace(/\{\{([a-z_]+)\}\}/g, (_, key) => {
      if (!(key in variables)) throw new Error(`Unknown template variable: ${key}`);
      return variables[key];
    });
    if (/\{\{|\}\}/.test(extra)) throw new Error('Invalid template placeholder');
    const target = path.join(envDir, id, 'terragrunt.hcl');
    const content = `${marker}\nterraform {\n  source = "${item.source}"\n}\n\n${root}\n${extra}`;
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') !== content) throw new Error(`Refusing to overwrite existing module ${id}; review its configuration`);
    pending.push({ target, content });
  }
  for (const { target, content } of pending) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
  return ordered.map(item => item.id);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    console.log(generate({ repository: process.cwd(), project: process.env.PROJECT_NAME, environment: process.env.ENVIRONMENT, modules: process.env.MODULES }).join(','));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
