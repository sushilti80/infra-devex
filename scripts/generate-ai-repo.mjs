#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, '.ai', 'ai-repo.md');

function read(path) {
  return readFileSync(join(ROOT, path), 'utf8');
}

function trackedFiles() {
  return execFileSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' })
    .split(/\r?\n/)
    .filter(Boolean)
    .filter((path) => path !== '.ai/ai-repo.md')
    .sort();
}

function directFiles(files, dir, extensions = []) {
  const prefix = dir + '/';
  return files
    .filter((path) => path.startsWith(prefix))
    .filter((path) => !path.slice(prefix.length).includes('/'))
    .filter((path) => extensions.length === 0 || extensions.some((ext) => path.endsWith(ext)))
    .filter((path) => !/\.(spec|test)\./.test(path) && !path.includes('.skip'))
    .sort();
}

function bullets(paths) {
  return paths.length ? paths.map((path) => '- `' + path + '`') : ['- None tracked.'];
}

function render() {
  const files = trackedFiles();
  const pkg = JSON.parse(read('package.json'));
  const config = read('config.js');

  const agents = directFiles(files, '.github/agents', ['.agent.md']);
  const skills = files.filter((path) => path.startsWith('.github/skills/') && path.endsWith('/SKILL.md')).sort();
  const workflows = directFiles(files, '.github/workflows', ['.yml', '.yaml']);
  const repositoryEvals = directFiles(files, '.agent/evals', ['.yml', '.yaml']);
  const routes = directFiles(files, 'routes', ['.js', '.cjs', '.mjs']);
  const services = directFiles(files, 'services', ['.js', '.cjs', '.mjs']);
  const middleware = directFiles(files, 'middleware', ['.js', '.cjs', '.mjs']);
  const utilities = directFiles(files, 'utils', ['.js', '.cjs', '.mjs']);
  const pages = directFiles(files, 'srcV2/pages', ['.vue']);
  const stores = directFiles(files, 'srcV2/stores', ['.ts']);
  const composables = directFiles(files, 'srcV2/composables', ['.ts']);
  const frontendServices = directFiles(files, 'srcV2/services', ['.ts']);
  const dataCatalogs = directFiles(files, 'data', ['.json']);
  const externalRepos = [...new Set(config.match(/Aya-DevOpsTeam\/[A-Za-z0-9._-]+/g) || [])].sort();
  const graphTracked = files.includes('graphify-out/graph.json');

  const lines = [
    '# AI Repository Map',
    '',
    '> Generated by `scripts/generate-ai-repo.mjs`. Do not edit manually.',
    '',
    '## How to use this map',
    '',
    '1. Read this file first for repository structure, ownership, and likely entry points.',
    '2. Use Graphify only for relationship/data-flow questions and only when its snapshot is available.',
    '3. Use targeted search for unresolved symbols or paths.',
    '4. Read the exact current file before editing it or making a file-specific claim.',
    '5. Use broad grep/tree enumeration only when the narrower layers cannot answer the question.',
    '',
    '## Repository identity',
    '',
    '- Package: `' + pkg.name + '`',
    '- Purpose: ' + pkg.description,
    '- Backend: Node.js / Express',
    '- Frontend: Vue 3 / TypeScript / Vite',
    '- Tracked Graphify snapshot: **' + (graphTracked ? 'yes' : 'no') + '**',
    '',
    '## Primary areas',
    '',
    '| Area | Purpose |',
    '| --- | --- |',
    '| `.agent/` | Agent governance enrollment, behavioral evals, operational state, and propose-only learning |',
    '| `.github/agents/` | Agent role definitions |',
    '| `.github/skills/` | Reusable task procedure and validation |',
    '| `.github/workflows/` | GitHub Actions workflows |',
    '| `.pipeline/` | Azure DevOps build/release pipeline definition |',
    '| `routes/` | Express HTTP routes |',
    '| `services/` | Backend domain and integration services |',
    '| `middleware/` | Express middleware |',
    '| `utils/` | Shared backend utilities |',
    '| `srcV2/` | Vue 3 frontend |',
    '| `data/` | Runtime catalogs |',
    '| `docs/` | Product, architecture, review, readiness, security, release, and operational docs |',
    '| `tests/` | Smoke, integration, E2E, and result artifacts |',
    '| `scripts/` | Deterministic repository tooling and operational scripts |',
    '',
    '## Where to look first',
    '',
    '| Need | First location |',
    '| --- | --- |',
    '| Repository orientation | `.ai/ai-repo.md` |',
    '| Agent governance enrollment | `.agent/governance.yaml` and `.github/workflows/agent-governance.yml` |',
    '| Pipeline operational state | `.agent/state/project-state.md` |',
    '| LearningRecord candidates | `.agent/learning/candidates/` |',
    '| Repository behavioral eval catalog | `.agent/evals/` |',
    '| Relationship/dependency question | `.github/skills/graphify-context/SKILL.md`, then Graphify if available |',
    '| Repository-wide invariants | `.github/copilot-instructions.md` |',
    '| Agent responsibility | `.github/agents/` |',
    '| Reusable procedure | `.github/skills/` |',
    '| API endpoint | `routes/api.js` |',
    '| GitHub operation | `services/githubService.js` |',
    '| Infrastructure metadata | `services/infrastructureService.js` and `.github/skills/service-catalog-metadata/SKILL.md` |',
    '| Live infrastructure evidence | `.github/skills/infrastructure-repo/SKILL.md` |',
    '| Frontend page | `srcV2/pages/` |',
    '| Feature requirement | `docs/prd/` |',
    '| Architecture contract | `docs/architecture/*-spec.json` |',
    '| QA evidence | `tests/results/` |',
    '| Release evidence | `docs/releases/` |',
    '',
    '## Agents',
    '',
    ...bullets(agents),
    '',
    '## Skills',
    '',
    ...bullets(skills),
    '',
    '## Repository behavioral evals',
    '',
    ...bullets(repositoryEvals),
    '',
    '## GitHub workflows',
    '',
    ...bullets(workflows),
    '',
    '## Backend modules',
    '',
    '### Routes',
    '',
    ...bullets(routes),
    '',
    '### Services',
    '',
    ...bullets(services),
    '',
    '### Middleware',
    '',
    ...bullets(middleware),
    '',
    '### Utilities',
    '',
    ...bullets(utilities),
    '',
    '## Vue frontend',
    '',
    '### Pages',
    '',
    ...bullets(pages),
    '',
    '### Stores',
    '',
    ...bullets(stores),
    '',
    '### Composables',
    '',
    ...bullets(composables),
    '',
    '### Frontend services',
    '',
    ...bullets(frontendServices),
    '',
    '## Data catalogs',
    '',
    ...bullets(dataCatalogs),
    '',
    '## External Aya repositories referenced by config',
    '',
    ...externalRepos.map((name) => '- `' + name + '`'),
    '',
    '## Package scripts',
    '',
    ...Object.entries(pkg.scripts || {}).map(([name, command]) => '- `npm run ' + name + '` — `' + command + '`'),
    '',
    '## Delivery artifact locations',
    '',
    '- Product requirements: `docs/prd/`',
    '- Architecture contracts: `docs/architecture/`',
    '- Challenger reviews: `docs/reviews/`',
    '- Debug evidence: `docs/debug/`',
    '- Readiness: `docs/readiness/`',
    '- Security scan evidence: `docs/security/`',
    '- Releases: `docs/releases/`',
    '- QA results: `tests/results/`',
    '',
    '## Freshness',
    '',
    'Check:',
    '',
    '```bash',
    'node scripts/generate-ai-repo.mjs --check',
    '```',
    '',
    'Regenerate:',
    '',
    '```bash',
    'node scripts/generate-ai-repo.mjs',
    '```',
    ''
  ];

  return lines.join('\n');
}

const expected = render();

if (process.argv.includes('--check')) {
  const actual = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (actual !== expected) {
    console.error('.ai/ai-repo.md is stale. Run: node scripts/generate-ai-repo.mjs');
    process.exit(1);
  }
  console.log('.ai/ai-repo.md is current.');
  process.exit(0);
}

writeFileSync(OUTPUT, expected, 'utf8');
console.log('Wrote .ai/ai-repo.md');
